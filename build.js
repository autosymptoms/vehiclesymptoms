const V=window.VEHICLES,CATS=['Warning Lights','Smoke','Leaks','Noises','Smells','Starting Problems','Driving'],ids=new Set();let bad=0;
V.forEach(v=>{if(ids.has(v.id)){console.log('DUP',v.id);bad++}ids.add(v.id);
 if(!/^[a-z0-9-]+$/.test(v.id)||v.years[0]<1996||v.years[1]>2026){console.log('BADV',v.id);bad++}
 v.issues.forEach(i=>{if(i.y[0]<v.years[0]||i.y[1]>v.years[1]||i.y[0]>i.y[1]||!CATS.includes(i.cat)||!['high','med','low'].includes(i.sev)||!i.t||!i.sym||!i.why||!i.next){console.log('BADI',v.id,i.t);bad++}})});
