// ---- Static site output (dist/) ----
const {JSDOM}=require('jsdom');
const SITE='https://vehiclesymptoms.com';
const tpl=fs.readFileSync('src/template.html','utf8');
const data=fs.readFileSync('vehicles.js','utf8');
fs.rmSync('dist',{recursive:true,force:true});fs.mkdirSync('dist');
fs.writeFileSync('dist/vehicles.js',data);fs.copyFileSync('src/app.js','dist/app.js');fs.copyFileSync('src/site.css','dist/site.css');
const escA=t=>t.replace(/&/g,'&amp;').replace(/"/g,'&quot;').replace(/</g,'&lt;');
const renderer=new JSDOM(tpl.replace('{{VEHHTML}}','').replace('<script src="/vehicles.js"></script>\n<script src="/app.js"></script>','<script>'+data+'</script><script>'+fs.readFileSync('src/app.js','utf8')+'</script>'),{runScripts:'dangerously',url:SITE+'/vehicles/x/'});
renderer.window.fetch=()=>new Promise(()=>{});renderer.window.scrollTo=()=>{};
const RW=renderer.window,RV=RW.VEHICLES;
function page(path,title,desc,veh){
  let h=tpl.replace(/{{TITLE}}/g,escA(title)).replace(/{{DESC}}/g,escA(desc)).replace(/{{CANON}}/g,SITE+path)
    .replace('{{HOMEHIDE}}',veh?' style="display:none"':'').replace('{{VEHSTYLE}}',veh?'':'display:none;');
  let inner='';
  if(veh){RW.eval(`state.q='';state.tab='All';renderVehicle(VEHICLES.find(x=>x.id==='${veh.v.id}'),${veh.y||null})`);inner=RW.document.getElementById('vehicleView').innerHTML;}
  h=h.replace('{{VEHHTML}}',()=>inner);
  const f='dist'+path+'index.html';fs.mkdirSync(require('path').dirname(f),{recursive:true});fs.writeFileSync(f,h);
  return path;
}
const urls=[page('/','VehicleSymptoms.com — What is your vehicle trying to tell you?','Free car symptom checker. Search warning lights, noises, smells, leaks, smoke and starting problems, decode your VIN, and see known problems for your exact year, make and model.')];
for(const v of V){
  const nm=v.make+' '+v.model;
  urls.push(page(`/vehicles/${v.id}/`,`${nm} Problems by Year — Known Issues | VehicleSymptoms.com`,`Known ${nm} problems from ${v.years[0]} to ${v.years[1]}: ${v.issues.slice(0,3).map(i=>i.t.toLowerCase()).join('; ')}. Symptoms, causes and what to do.`,{v}));
  for(let y=v.years[0];y<=v.years[1];y++){
    const is=v.issues.filter(i=>y>=i.y[0]&&y<=i.y[1]);
    urls.push(page(`/vehicles/${v.id}/${y}/`,`${y} ${nm} Problems & Symptoms | VehicleSymptoms.com`,
      is.length?`${is.length} known problem${is.length>1?'s':''} for the ${y} ${nm}: ${is.slice(0,3).map(i=>i.t.toLowerCase()).join('; ')}. Plus safety recalls and what to do.`:`Common symptoms, safety recalls and what to do for the ${y} ${nm}. Free, plain-English guide.`,{v,y}));
  }
}
fs.writeFileSync('dist/sitemap.xml','<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+urls.map(u=>`<url><loc>${SITE}${u}</loc></url>`).join('\n')+'\n</urlset>\n');
fs.writeFileSync('dist/robots.txt',`User-agent: *\nAllow: /\nSitemap: ${SITE}/sitemap.xml\n`);
console.log('dist pages:',urls.length);
